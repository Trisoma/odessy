"""Current-user Linux integration: owned launcher, menu entry, maintenance cache.

The contract matches the Windows adapter so the installer, lifecycle and bridge do
not branch on the platform: ``launch``, ``register``, ``refresh``, ``unregister`` and
``helper_cleanup``.

Registration owns exactly two files: ``launch.sh`` inside the installation and
``odessy-<identity>.desktop`` under the XDG application directory. Both are recorded
with digests, and only unchanged files are ever removed.
"""
from __future__ import annotations
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

from .maintenance import ManagedInstallation, digest, guard, read_json

DISPLAY_VERSION='0.5.0.dev0'
DESKTOP_NAME='desktop/odessy_desktop'
_IDENTITY=re.compile('[a-f0-9]{32}')
_DIGEST=re.compile('[a-f0-9]{64}')

# Written as an owned file and digest-verified on every refresh. The active version
# is read from the record rather than remembered here, so a rollback only needs a
# refresh instead of a re-registration.
_LAUNCHER=r'''#!/bin/sh
# Generated by Odessy setup. Owned and digest-verified by the installation record.
set -eu
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
active=$(sed -n 's/.*"active"[[:space:]]*:[[:space:]]*"\([a-f0-9]\{32\}\)".*/\1/p' "$here/installation.json" | head -n 1)
if [ -z "$active" ]; then
  echo "Odessy installation record has no active version" >&2
  exit 1
fi
exe="$here/versions/$active/desktop/odessy_desktop"
case "${1:-}" in
  --manage) shift; exec "$exe" --manage --install-root "$here" "$@" ;;
  --uninstall) shift; exec "$exe" --uninstall --install-root "$here" "$@" ;;
  *) exec "$exe" --installed --install-root "$here" "$@" ;;
esac
'''


def _identity(record):
    identity=record.get('id')
    if not isinstance(identity,str) or not _IDENTITY.fullmatch(identity):
        raise ValueError('invalid installation identity')
    return identity


def _data_home():
    """The per-user data directory, honouring XDG_DATA_HOME when it is set."""
    value=os.environ.get('XDG_DATA_HOME')
    if value: return Path(value)
    return Path(os.environ.get('HOME') or Path.home())/'.local/share'


def _launcher(root):
    return guard(root/'launch.sh')


def _menu_entry(identity):
    return guard(_data_home()/'applications'/('odessy-'+identity+'.desktop'))


def _cache_root():
    return _data_home()/'odessy'/'maintenance'


def _active_desktop(root,record):
    version=record.get('active')
    if not isinstance(version,str) or not _IDENTITY.fullmatch(version):
        raise ValueError('the installation has no active version')
    desktop=guard(root/'versions'/version/DESKTOP_NAME)
    if not desktop.is_file(): raise ValueError('installed desktop is unavailable')
    return version,desktop


def launch(root,mode='app',launch_id=None):
    """Start the recorded desktop for a mode and return the child process."""
    if mode not in ('app','manage','uninstall'): raise ValueError('invalid launch mode')
    root=guard(root)
    record=ManagedInstallation(root).record()
    _,executable=_active_desktop(root,record)
    args=[str(executable)]
    if mode in ('manage','uninstall'):
        args+=['--'+mode,'--install-root',str(root)]
        resources=record.get('linux_registration') or {}
        helper=resources.get('helper')
        if isinstance(helper,str) and helper: args+=['--payload',helper]
    else:
        args+=['--installed','--install-root',str(root)]
    if launch_id is not None:
        from . import launch_receipts
        launch_receipts.prepare(root,launch_id)
        args+=['--launch-id',launch_id]
    # Same rule as the Windows launcher: the long-lived desktop must not inherit the
    # stdio bridge's response pipes, and it must outlive the shell that started it.
    return subprocess.Popen(args,cwd=tempfile.gettempdir(),stdin=subprocess.DEVNULL,
                            stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL,
                            close_fds=True,start_new_session=True)


def _quote_exec(value):
    """Quote one Exec argument for a desktop entry."""
    if ' ' in value or '\t' in value or '"' in value:
        return '"'+value.replace('\\','\\\\').replace('"','\\"')+'"'
    return value


def _entry_text(launcher,helper):
    base=_quote_exec(str(launcher))
    payload=(' --payload '+_quote_exec(str(helper))) if helper else ''
    return '\n'.join([
        '[Desktop Entry]',
        'Type=Application',
        'Version=1.0',
        'Name=Odessy',
        'Comment=Local assistant owned by you',
        'Exec='+base,
        'Terminal=false',
        'Categories=Utility;',
        'Actions=Manage;Uninstall;',
        '',
        '[Desktop Action Manage]',
        'Name=Manage Odessy',
        'Exec='+base+' --manage'+payload,
        '',
        '[Desktop Action Uninstall]',
        'Name=Uninstall Odessy',
        'Exec='+base+' --uninstall'+payload,
        '',
    ])


def _cache_helper(root,record,payload):
    """Persist a verified maintenance payload outside the installation."""
    from .package_context import context
    payload=guard(payload)
    context(payload=payload,root=root)
    manifest=read_json(payload/'setup-context.json')
    key_hash=hashlib.sha256(json.dumps(manifest,sort_keys=True).encode()).hexdigest()[:32]
    helper=guard(_cache_root()/record['id']/key_hash)
    helper.mkdir(parents=True,exist_ok=True)
    for name,sha in manifest['files'].items():
        target=guard(helper/name)
        if target.exists():
            if digest(target)!=sha: raise ValueError('maintenance helper changed')
            continue
        target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(guard(payload/name),target)
        if digest(target)!=sha: raise ValueError('maintenance helper copy failed verification')
    (helper/'setup-context.json').write_text(json.dumps(manifest),encoding='utf-8')
    context(payload=helper,root=root)
    return helper


def register(root,record,payload=None):
    """Create the launcher, the application-menu entry and the maintenance cache.

    Identity and ownership are validated before anything is written. The launcher is
    written before the menu entry so the entry never points at a missing file.
    """
    root=guard(root)
    if record.get('root')!=str(root): raise ValueError('registration root mismatch')
    identity=_identity(record)
    version,desktop=_active_desktop(root,record)
    previous=record.get('linux_registration') or {}
    if previous and previous.get('installation_id') not in (None,identity):
        raise ValueError('registration belongs to another installation')
    helper=previous.get('helper')
    helper_files=previous.get('helper_files')
    if payload is not None:
        helper=str(_cache_helper(root,record,payload))
        helper_files=dict(read_json(Path(helper)/'setup-context.json')['files'])
        helper_files['setup-context.json']=digest(Path(helper)/'setup-context.json')
    if helper: helper=guard(Path(helper))
    if helper and not (helper/DESKTOP_NAME).is_file():
        raise ValueError('maintenance payload lacks the desktop application')
    launcher=_launcher(root)
    if launcher.exists() and digest(launcher)!=previous.get('files',{}).get(str(launcher)):
        raise ValueError('launcher is externally owned or modified')
    entry=_menu_entry(identity)
    if entry.exists() and digest(entry)!=previous.get('files',{}).get(str(entry)):
        raise ValueError('application menu entry is externally owned or modified')
    launcher.write_text(_LAUNCHER,encoding='utf-8')
    launcher.chmod(0o755)
    entry.parent.mkdir(parents=True,exist_ok=True)
    entry.write_text(_entry_text(launcher,helper),encoding='utf-8')
    entry.chmod(0o644)
    resources={'schema_version':1,'installation_id':identity,'version':version,
               'files':{str(launcher):digest(launcher),str(entry):digest(entry)},
               'launcher':str(launcher),'menu_entry':str(entry),'desktop_exec':str(desktop),
               'helper':str(helper) if helper else None,'state':'complete'}
    if helper_files is not None: resources['helper_files']=helper_files
    record['linux_registration']=resources
    return resources


def refresh(root,record):
    """Keep the menu entry pointing at the version that is actually active."""
    resources=record.get('linux_registration') or {}
    if resources.get('state')!='complete' or not resources.get('menu_entry'):
        return resources
    root=guard(root)
    _,desktop=_active_desktop(root,record)
    entry=guard(Path(resources['menu_entry']))
    if entry.exists() and digest(entry)!=resources.get('files',{}).get(str(entry)):
        raise ValueError('application menu entry was modified externally; re-register from management')
    helper=resources.get('helper')
    helper=guard(Path(helper)) if isinstance(helper,str) and helper else None
    entry.parent.mkdir(parents=True,exist_ok=True)
    entry.write_text(_entry_text(guard(Path(resources['launcher'])),helper),encoding='utf-8')
    entry.chmod(0o644)
    resources.setdefault('files',{})[str(entry)]=digest(entry)
    resources['desktop_exec']=str(desktop)
    record['linux_registration']=resources
    return resources


def unregister(root,record):
    """Remove only the recorded menu entry and launcher when they still match."""
    root=guard(root)
    resources=record.get('linux_registration') or {}
    identity=_identity(record)
    retained=[]
    # Only exact known paths can be removed, even if the ownership record is edited.
    allowed={str(_launcher(root)),str(_menu_entry(identity))}
    for name,sha in resources.get('files',{}).items():
        if name not in allowed: raise ValueError('invalid registration ownership path')
        path=guard(name)
        if path.is_file() and digest(path)==sha: path.unlink()
        elif path.exists(): retained.append(name)
    return retained


def helper_cleanup(record):
    """Remove only recorded, unchanged cache files; never schedule self-deletion."""
    resources=record.get('linux_registration') or {}
    helper=resources.get('helper')
    if not isinstance(helper,str) or not helper: return {'state':'none'}
    try:
        path=guard(Path(helper))
        identity=_identity(record)
        if path.parent!=guard(_cache_root()/identity) or not _IDENTITY.fullmatch(path.name):
            return {'state':'retained','reason':'cache does not belong to this installation'}
    except ValueError:
        return {'state':'retained','reason':'unsafe cache path'}
    if not path.is_dir(): return {'state':'absent'}
    current=Path(sys.executable).resolve()
    if current.is_relative_to(path.resolve()):
        return {'state':'retained','reason':'maintenance helper is running; no deletion scheduled'}
    inventory=resources.get('helper_files')
    if not isinstance(inventory,dict) or not inventory or len(inventory)>100001:
        return {'state':'retained','reason':'cache has no recorded ownership inventory'}
    files=[];directories={path}
    try:
        for name,sha in inventory.items():
            if (not isinstance(name,str) or not name or name.startswith('/') or '..' in Path(name).parts
                    or not _DIGEST.fullmatch(str(sha))):
                raise ValueError('invalid cache ownership inventory')
            target=guard(path/name)
            if not target.is_relative_to(path) or target==path: raise ValueError('invalid cache target')
            files.append((target,sha))
            directories.update(parent for parent in target.parents if parent.is_relative_to(path))
    except (OSError,ValueError):
        return {'state':'retained','reason':'unsafe cache ownership inventory'}
    removed=[];retained=[]
    for target,sha in files:
        try:
            guard(target)
            if target.is_file() and digest(target)==sha:
                target.unlink();removed.append(str(target.relative_to(path)))
            elif target.exists(): retained.append(str(target.relative_to(path)))
        except (OSError,ValueError): retained.append(str(target.relative_to(path)))
    for directory in sorted(directories,key=lambda p:len(p.parts),reverse=True):
        try: guard(directory).rmdir()
        except (OSError,ValueError): pass  # Nonempty directories contain retained files.
    return {'state':'retained' if path.exists() else 'removed','removed':removed,
            'retained':retained,'reason':'only unchanged recorded files are removed; other files stay'}
