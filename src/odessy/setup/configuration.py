"""Explicit, create-only configuration export; never overwrite user settings."""
from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path

from .contracts import public
from .planning import SetupPlan, build_plan


def destination(value: str | Path) -> Path:
    path = Path(value).expanduser()
    # Do not resolve a symlink at the destination into a different write target.
    if path.is_symlink():
        raise ValueError('configuration destination must not be a symlink')
    return path.parent.resolve() / path.name


def consent_id(plan: SetupPlan, output: Path | None, env_output: Path | None) -> str:
    import hashlib
    payload = [plan.plan_id, str(output) if output else None, str(env_output) if env_output else None]
    return hashlib.sha256(json.dumps(payload, separators=(',', ':')).encode()).hexdigest()


def write_new(path: Path, content: str) -> None:
    """Publish fully written bytes atomically without replacing any existing file."""
    if path.exists() or path.is_symlink():
        raise ValueError('destination already exists; existing configuration was not changed')
    if not path.parent.is_dir():
        raise ValueError('destination parent must already exist')
    fd, temporary = tempfile.mkstemp(prefix='.odessy-setup-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(content); stream.flush(); os.fsync(stream.fileno())
        # Hard-link publication refuses a raced-in destination on Windows and Unix.
        os.link(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def export_selection(plan: SetupPlan, path: Path) -> None:
    if plan != build_plan(plan.selection):
        raise ValueError('plan changed after review; rebuild it before export')
    write_new(path, json.dumps({'schema_version': plan.schema_version, 'selection': public(plan.selection)}, indent=2) + '\n')


def export_environment(plan: SetupPlan, path: Path) -> None:
    write_new(path, environment_text(plan))


def environment_text(plan: SetupPlan) -> str:
    if plan != build_plan(plan.selection):
        raise ValueError('plan changed after review; rebuild it before export')
    # Compare against detected local selection, not GUI metadata.
    from .contracts import SetupSelection
    local = SetupSelection(role=plan.selection.role)
    if (plan.selection.platform, plan.selection.architecture) != (local.platform, local.architecture):
        raise ValueError('selection platform/architecture belongs to another machine')
    if not plan.selection.model:
        raise ValueError('no model configured: refusing an env file that would silently fall back to LFM')
    if plan.selection.model.credential_env:
        from .verification import KEY_ENV
        key = plan.selection.model.credential_env
        if key not in ('ODESSY_CLOUD_API_KEY', KEY_ENV.get(plan.selection.model.provider)):
            raise ValueError('runtime does not support this credential variable; use the provider variable or ODESSY_CLOUD_API_KEY')
    voice = plan.selection.voice
    required = ([] if voice.stt_provider != 'whisper.cpp' else ['ODESSY_WHISPER_BIN', 'ODESSY_WHISPER_MODEL']) + ([] if voice.tts_provider != 'kokoro' else ['ODESSY_KOKORO_MODEL', 'ODESSY_KOKORO_VOICES'])
    if voice.enabled and any(not plan.environment.get(key) for key in required):
        raise ValueError('complete the selected provider voice paths or disable voice before exporting runtime configuration')
    content = '# Generated by Odessy setup; credentials are supplied separately.\n'
    content += '# Set ODESSY_CONFIG_FILE to this file; existing shell variables take precedence.\n'
    content += '\n'.join(f'{key}="{value}"' for key, value in sorted(plan.environment.items())) + '\n'
    return content
